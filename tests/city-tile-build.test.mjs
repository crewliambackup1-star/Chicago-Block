import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const builder = resolve(root, 'scripts/build-city-tiles.mjs');

test('city tile builder creates schema-shaped output from local GeoJSON fixtures', async () => {
  const dataRoot = await mkdtemp(resolve(tmpdir(), 'chicago-city-tiles-'));
  const rawRoot = resolve(dataRoot, 'raw');
  const outputRoot = resolve(dataRoot, 'tiles');
  try {
    await mkdir(rawRoot, { recursive: true });
    await mkdir(outputRoot, { recursive: true });

    const manifest = JSON.parse(
      await readFile(resolve(root, 'city-data/manifest.json'), 'utf8')
    );
    await writeFile(resolve(dataRoot, 'manifest.json'), JSON.stringify(manifest));

    const streets = {
      type: 'FeatureCollection',
      features: [{
        type: 'Feature',
        id: 'fixture-street-1',
        properties: { name: 'Test Avenue', lanes: 2 },
        geometry: {
          type: 'LineString',
          coordinates: [
            [-87.6298, 41.8781],
            [-87.6288, 41.8781]
          ]
        }
      }]
    };
    const buildings = {
      type: 'FeatureCollection',
      features: [{
        type: 'Feature',
        id: 'fixture-building-1',
        properties: { stories: 3, year_built: 1920 },
        geometry: {
          type: 'Polygon',
          coordinates: [[
            [-87.6298, 41.8781],
            [-87.6297, 41.8781],
            [-87.6297, 41.8782],
            [-87.6298, 41.8782],
            [-87.6298, 41.8781]
          ]]
        }
      }]
    };
    await Promise.all([
      writeFile(resolve(rawRoot, 'streets.geojson'), JSON.stringify(streets)),
      writeFile(resolve(rawRoot, 'buildings.geojson'), JSON.stringify(buildings)),
      writeFile(resolve(outputRoot, 'keep-me.txt'), 'not generated by the tile builder'),
      writeFile(resolve(outputRoot, '99_99.json'), '{}')
    ]);

    const result = spawnSync(process.execPath, [builder], {
      encoding: 'utf8',
      timeout: 30000,
      env: { ...process.env, CHICAGO_CITY_DATA_DIR: dataRoot }
    });
    assert.equal(result.status, 0, result.stderr || result.stdout);
    assert.match(result.stdout, /Built 1 Chicago tiles from 1 street features and 1 building features/);

    const outputManifest = JSON.parse(
      await readFile(resolve(outputRoot, 'manifest.json'), 'utf8')
    );
    assert.equal(outputManifest.tileCount, 1);
    assert.equal(outputManifest.tiles[0].tileId, '0:0');

    const tile = JSON.parse(await readFile(resolve(outputRoot, '0_0.json'), 'utf8'));
    assert.equal(tile.schemaVersion, 1);
    assert.equal(tile.tileId, '0:0');
    assert.equal(tile.bounds.minX, 0);
    assert.equal(tile.source.publisher, 'City of Chicago');
    assert.equal(tile.streets.length, 1);
    assert.equal(tile.buildings.length, 1);
    assert.equal(tile.streets[0].properties.name, 'Test Avenue');
    assert.equal(tile.buildings[0].properties.stories, 3);

    const outputs = await readdir(outputRoot);
    assert.ok(outputs.includes('keep-me.txt'), 'non-generated files should be preserved');
    assert.ok(!outputs.includes('99_99.json'), 'old generated tile files should be replaced');
  } finally {
    await rm(dataRoot, { recursive: true, force: true });
  }
});
